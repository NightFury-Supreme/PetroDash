Object.keys(translations).forEach(loc => {
  const filePath = path.join(localesDir, `${loc}.json`);
  if (!fs.existsSync(filePath)) return;
  
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  
  if (!data.Tickets) data.Tickets = {};
  if (!data.BackendErrors) data.BackendErrors = {};
  
  // Apply translated keys
  data.Tickets = { ...data.Tickets, ...translations[loc].Tickets };
  data.BackendErrors = { ...data.BackendErrors, ...translations[loc].BackendErrors };
  
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n');
});

